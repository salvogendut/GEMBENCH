"""genfont - generate a GEOBENCH font set (.FNT) from built-in glyph art.

A font set is a 16-byte header followed by fixed-width glyph bitmaps, one byte
per row (glyphs are <= 8 px wide). The desktop loads it like an icon set: it is
read off disk, validated, and drawn by lib/text.asm, which reads the geometry
(first/last char, width, height) straight from the header.

Header (16 bytes):
    0-3   magic "GBFN"
    4     version (1)
    5     first char code
    6     last char code
    7     width in pixels (<= 8)
    8     height in rows
    9     bytes per row (1 for width <= 8)
    10-15 reserved (0)

Then (last-first+1) * height bytes: each glyph row is one byte, the top
`width` bits are pixels (bit 7 = leftmost), the rest are 0.

The glyphs below are a readable 5x7 body laid out in a 6x8 cell: five pixels of
glyph in bits 7..3, the 6th pixel (bit 2) is always blank so it acts as the
inter-character gap, and the 8th row leaves room for descenders (g j p q y).

Usage:
    tools/genfont.py <out.FNT>
"""
