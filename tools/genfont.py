def glyph_bytes(art):
    rows = list(art)
    if len(rows) > HEIGHT:
        raise SystemExit(f"glyph too tall ({len(rows)} rows): {art!r}")
    rows += ["     "] * (HEIGHT - len(rows))     # pad to full cell height
    out = bytearray()
    for r in rows:
        if len(r) != 5:
            raise SystemExit(f"row not 5 wide: {r!r} in {art!r}")
        bits = 0
        for i, ch in enumerate(r):
            if ch == '#':
                bits |= 1 << (4 - i)             # bit4 = leftmost of 5
        out.append((bits << 3) & 0xFF)           # 5 px in bits 7..3, gap below
    return bytes(out)


def main(argv):
    if len(argv) != 2:
        sys.exit("usage: genfont.py <out.FNT>")
    out = argv[1]
    last = 127
    header = bytearray(16)
    header[0:4] = MAGIC
    header[4] = VERSION
    header[5] = FIRST
    header[6] = last
    header[7] = WIDTH
    header[8] = HEIGHT
    header[9] = 1                                 # bytes per row
    blob = bytearray()
    for code in range(FIRST, last + 1):
        ch = chr(code)
        art = G.get(ch, [])                       # unknown -> blank glyph
        blob += glyph_bytes(art)
    with open(out, 'wb') as f:
        f.write(header)
        f.write(blob)
    total = HDR + len(blob)
    print(f"{out}: {last - FIRST + 1} glyphs {WIDTH}x{HEIGHT}, {total} bytes")


if __name__ == '__main__':
    main(sys.argv)
