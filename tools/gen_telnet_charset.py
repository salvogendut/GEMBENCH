#!/usr/bin/env python3
"""Generate apps/telnet/charset.h - an 8x8 ASCII charset (chars 32..127) for the
TELNET app's Mode-2 80x25 fullscreen renderer, extracted from build/CLASSIC.FNT
(the GEOBENCH 8x8 font: 16-byte header + 96 glyphs * 8 bytes, bit7 = leftmost px).

  tools/gen_telnet_charset.py            # build/CLASSIC.FNT -> apps/telnet/charset.h
Re-run + commit charset.h if the 8x8 font ever changes.
"""
import sys, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fnt = os.path.join(root, "build", "CLASSIC.FNT")
out = os.path.join(root, "apps", "telnet", "charset.h")

d = open(fnt, "rb").read()
first, w, h = d[5], d[7], d[8]
assert w == 8 and h == 8 and first == 32, f"expected 8x8 from char 32, got {w}x{h}@{first}"
glyphs = d[16:16 + 96 * 8]
assert len(glyphs) == 768, f"expected 768 glyph bytes, got {len(glyphs)}"

with open(out, "w") as f:
    f.write("/* charset.h - 8x8 ASCII glyphs (chars 32..127) for the TELNET Mode-2 80x25\n")
    f.write(" * renderer. GENERATED by tools/gen_telnet_charset.py from build/CLASSIC.FNT -\n")
    f.write(" * do not edit by hand. Each glyph = 8 bytes (one per scan line, bit7 = leftmost). */\n")
    f.write("#ifndef TELNET_CHARSET_H\n#define TELNET_CHARSET_H\n")
    f.write("#define FS_GLYPH0 32\n")
    f.write("static const unsigned char fs_charset[96 * 8] = {\n")
    for c in range(96):
        row = ", ".join("0x%02X" % glyphs[c * 8 + r] for r in range(8))
        f.write("    %s,   /* '%s' */\n" % (row, chr(32 + c) if 32 + c != 92 else "\\\\"))
    f.write("};\n#endif\n")

print("wrote", out, "(96 glyphs)")
