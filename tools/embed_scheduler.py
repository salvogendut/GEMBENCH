#!/usr/bin/env python3
"""Generate an SDAS object source that installs an app-carried scheduler."""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("payload", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--base", required=True, type=lambda value: int(value, 0))
    args = parser.parse_args()

    data = args.payload.read_bytes()
    if not data:
        raise SystemExit(f"empty scheduler payload: {args.payload}")
    if len(data) > 512:
        raise SystemExit(f"scheduler payload is {len(data)} bytes; maximum is 512")
    if not 0 <= args.base <= 0xFFFF:
        raise SystemExit("scheduler base must fit in 16 bits")

    lines = [
        "; Generated by tools/embed_scheduler.py. Do not edit.",
        "        .module gbtaskroot",
        "        .globl  _gb_task_root_init",
        "        .area   _CODE",
        "_gb_task_root_init::",
        "        di",
        "        ld      hl, #scheduler_payload",
        f"        ld      de, #0x{args.base:04X}",
        f"        ld      bc, #0x{len(data):04X}",
        "        ldir",
        f"        call    0x{args.base:04X}",
        "        ei",
        "        ret",
        "scheduler_payload:",
    ]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("        .db     " + ", ".join(f"0x{byte:02X}" for byte in chunk))

    args.output.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
